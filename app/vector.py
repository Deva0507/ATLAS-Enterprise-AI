"""
Pinecone vector database operations for the Atlas application.

This module manages:
    - Pinecone client and index initialization.
    - Automatic index creation when the index does not exist.
    - Tenant-specific namespace management.
    - Vector upsert operations.
    - Metadata-filtered similarity search.
    - Document vector deletion.

The module is embedding-provider independent. It works with vectors
generated by OpenAI, Anthropic-compatible embedding providers, or
other embedding models, provided their dimensions match the index.
"""

import logging
import time
from functools import lru_cache

from pinecone import Pinecone, ServerlessSpec

from app.config import settings
from app.observability import trace


# Module-level logger for tracking Pinecone operations and errors.
log = logging.getLogger(__name__)


@lru_cache(maxsize=1)
def index():
    """
    Initialize and return the configured Pinecone index.

    This function:
        1. Loads Pinecone configuration from application settings.
        2. Validates the API key and index name.
        3. Connects to Pinecone.
        4. Checks whether the configured index exists.
        5. Creates the index if it does not exist.
        6. Validates the index dimension and similarity metric.
        7. Waits until the index becomes ready.
        8. Returns the initialized Pinecone index handle.

    Returns:
        pinecone.Index:
            An initialized Pinecone index object.

    Raises:
        RuntimeError:
            If the Pinecone API key or index name is missing.

        ValueError:
            If the existing index dimension or similarity metric
            does not match the application configuration.

        TimeoutError:
            If the index does not become ready within the configured
            readiness timeout.

        Exception:
            Propagates unexpected authentication, network, and
            Pinecone API errors.

    Notes:
        - lru_cache ensures the index is initialized only once per process.
        - The index dimension must match EMBED_DIM in application settings.
        - Cosine similarity is used for vector similarity search.
        - The index must be ready before application operations proceed.
    """

    # Load application configuration.
    s = settings()

    # Validate required Pinecone configuration.
    if not s.pinecone_api_key:
        raise RuntimeError("PINECONE_API_KEY is missing from .env")

    if not s.pinecone_index_name:
        raise RuntimeError("PINECONE_INDEX_NAME is missing from .env")

    # Initialize the Pinecone client.
    pc = Pinecone(api_key=s.pinecone_api_key)

    name = s.pinecone_index_name

    # Check whether the configured index already exists.
    # describe_index() avoids listing all indexes unnecessarily.
    try:
        info = pc.describe_index(name)

    except Exception as exc:

        # Create the index only when Pinecone explicitly reports
        # that the requested index does not exist.
        # Authentication and network errors are propagated.
        if getattr(exc, "status", None) != 404:
            raise

        log.info(
            "Creating Pinecone index %s (dimension=%d, metric=cosine)",
            name,
            s.embed_dim
        )

        try:
            # Create a serverless Pinecone index.
            pc.create_index(
                name=name,
                dimension=s.embed_dim,
                metric="cosine",
                spec=ServerlessSpec(
                    cloud=s.pinecone_cloud,
                    region=s.pinecone_region
                )
            )

        except Exception as create_exc:

            # Handle concurrent initialization:
            # another application instance may have created the index.
            if getattr(create_exc, "status", None) != 409:
                raise

        # Retrieve index information after creation.
        info = pc.describe_index(name)

    # Validate the existing index dimension.
    # The dimension must match the configured embedding dimension.
    if int(info.dimension) != s.embed_dim:
        raise ValueError(
            f"Pinecone index {name} dimension={info.dimension}, "
            f"expected {s.embed_dim}. "
            "Use a different index name or matching EMBED_DIM."
        )

    # Validate the similarity metric.
    # This application expects cosine similarity.
    if str(info.metric).lower() != "cosine":
        raise ValueError(
            f"Pinecone index {name} must use cosine metric, "
            f"got {info.metric}"
        )

    # Wait until Pinecone reports that the index is ready.
    deadline = time.monotonic() + s.pinecone_ready_timeout

    while not pc.describe_index(name).status["ready"]:

        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"Pinecone index {name} was not ready within "
                f"{s.pinecone_ready_timeout}s"
            )

        # Avoid continuously polling the Pinecone API.
        time.sleep(3)

    log.info("Pinecone index %s ready", name)

    # Return the index handle for subsequent database operations.
    return pc.Index(name)


def namespace(tenant):
    """
    Generate an isolated Pinecone namespace for a tenant.

    Namespaces logically separate vector records belonging to
    different tenants within the same Pinecone index.

    Args:
        tenant (str):
            Unique tenant identifier.

    Returns:
        str:
            Tenant-specific namespace.

    Example:
        namespace("company-123")
        -> "tenant-company-123"

    Security:
        Always derive the tenant identifier from authenticated,
        server-side identity information. Never trust a tenant ID
        supplied directly by an unverified client.
    """

    return "tenant-" + tenant


@trace("upsert")
def upsert(tenant, records):
    """
    Insert or update vector records in the tenant's namespace.

    Pinecone upsert creates new records or replaces existing records
    when their vector IDs already exist.

    Args:
        tenant (str):
            Tenant identifier used to determine the namespace.

        records (list):
            Vector records containing IDs, embeddings, and optional
            metadata.

            Example:
                [
                    {
                        "id": "document-001",
                        "values": [0.12, 0.45, ...],
                        "metadata": {
                            "source": "policy.pdf",
                            "owner_sub": "user-123"
                        }
                    }
                ]

    Returns:
        UpsertResponse:
            Pinecone response containing the upsert operation details.

    Notes:
        - Records are stored within the specified tenant namespace.
        - Vector dimensions must match the Pinecone index dimension.
        - Existing records with identical IDs are overwritten.
        - The operation is traced without capturing function inputs
          or outputs.
    """

    return index().upsert(
        vectors=records,
        namespace=namespace(tenant)
    )


@trace("search")
def search(tenant, vector, groups, owner, limit=5):
    """
    Perform tenant-isolated, metadata-filtered vector similarity search.

    The search retrieves the most relevant vectors while enforcing
    metadata-based access control.

    A record is eligible for retrieval when either:
        1. Its allowed_groups metadata contains one of the user's groups.
        2. Its owner_sub metadata matches the authenticated user's ID.

    Both conditions are evaluated within the tenant's namespace.

    Args:
        tenant (str):
            Tenant identifier used to isolate the search namespace.

        vector (list[float]):
            Query embedding generated using the configured embedding model.

        groups (iterable):
            Groups associated with the authenticated user.

        owner (str):
            Authenticated user's unique identifier.

        limit (int, optional):
            Maximum number of matching records to retrieve.
            Defaults to 5.

    Returns:
        list[dict]:
            Matching records containing:
                - id: Pinecone vector ID.
                - score: Similarity score.
                - metadata: Associated record metadata.

    Security:
        - Tenant namespaces provide logical tenant isolation.
        - Metadata filters enforce group-based or owner-based retrieval.
        - Tenant, owner, and group values must originate from trusted
          server-side authentication and authorization logic.

    Notes:
        - Metadata must contain the expected allowed_groups and owner_sub
          fields for the access-control filter to work correctly.
        - The query embedding dimension must match the index dimension.
        - Similarity scores are not guaranteed to represent calibrated
          probabilities or factual relevance.
    """

    # Construct the metadata-based access-control filter.
    # A record is accessible if the user belongs to an allowed group
    # OR the user is its designated owner.
    acl = {
        "$or": [
            {"allowed_groups": {"$in": list(groups)}},
            {"owner_sub": {"$eq": owner}}
        ]
    }

    # Execute similarity search within the tenant-specific namespace.
    result = index().query(
        vector=vector,
        top_k=limit,
        include_metadata=True,
        namespace=namespace(tenant),
        filter=acl
    )

    # Return a simplified representation of the search results.
    return [
        {
            "id": match.id,
            "score": match.score,
            "metadata": match.metadata or {}
        }
        for match in result.matches
    ]


def delete_document(tenant, ids):
    """
    Delete document vectors from the tenant's Pinecone namespace.

    Args:
        tenant (str):
            Tenant identifier used to determine the namespace.

        ids (list[str]):
            Pinecone vector IDs associated with the document.

    Returns:
        None:
            No explicit return value.

    Notes:
        - Deletes only the supplied vector IDs.
        - Deletion is restricted to the specified tenant namespace.
        - An empty ID list is ignored to avoid unnecessary API calls.
        - Ensure the IDs belong to the document and tenant being deleted.
    """

    # Skip the Pinecone API call when there are no vector IDs.
    if ids:
        index().delete(
            ids=ids,
            namespace=namespace(tenant)
        )